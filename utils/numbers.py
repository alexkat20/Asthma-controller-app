"""Разбор чисел из свободного текста пользователя."""

import re

# Дробная часть — максимум 2 цифры и после неё нет ещё цифр: тогда
# "450,5" -> 450.5, но "450,460,470" (запятые-разделители без пробелов)
# корректно разбирается как три отдельных показания, а не [450.46, 470].
_NUMBER_RE = re.compile(r"\d+(?:[.,]\d{1,2}(?!\d))?")


def extract_numbers(text: str) -> list:
    return [float(n.replace(",", ".")) for n in _NUMBER_RE.findall(text)]
